def _profile_influence_note(name: str, matrix: ComparisonMatrix) -> str:
    """Generate a plain-English influence note."""
    if not matrix.rankings:
        return ""
    top = matrix.rankings[0]
    if not top.dimensions:
        return ""

    # Find the highest-weighted dimension where the winner excels
    weights = _get_profile_weights(name)
    if not weights:
        return ""

    best_dim = None
    best_impact = 0.0
    for ds in top.dimensions:
        w = weights.get(ds.dimension.value, 0)
        impact = ds.score * w
        if impact > best_impact:
            best_impact = impact
            best_dim = ds.dimension

    if best_dim:
        dim_label = best_dim.value.replace("_", " ").title()
        profile_label = name.replace("_", " ").title()
        return (
            f"{profile_label} profile favored {top.model_name} "
            f"due to strong {dim_label} performance."
        )
    return ""


