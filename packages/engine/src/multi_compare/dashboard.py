def _esc(text: str) -> str:
    """HTML-escape text."""
    return html.escape(str(text))


def _score_class(score: float) -> str:
    if score >= 0.8:
        return "pass"
    elif score >= 0.5:
        return "warn"
    return "fail"


def _score_color(score: float) -> str:
    if score >= 0.8:
        return "#6ee7b7"
    elif score >= 0.5:
        return "#fbbf24"
    return "#f87171"


def _detect_mode(report: MultiCompareReport) -> str:
    """Detect analysis mode from report context."""
    for rec in report.recommendations:
        if "STRICT" in rec.upper():
            return "STRICT"
    # Check gate checks for strict mode indicators
    for gc in report.gate_result.checks:
        if "strict" in gc.reason.lower():
            return "STRICT"
    return "EXPLORATORY"


def _compute_parity_status(parity_reports: list[CoverageParityReport]) -> str:
    """Compute overall parity status from reports."""
    if not parity_reports:
        return "OK"
    for p in parity_reports:
        if p.parity_warning and "invalid" in p.parity_warning.lower():
            return "INVALID"
    for p in parity_reports:
        if p.parity_warning and ("below" in p.parity_warning.lower() or "degraded" in p.parity_warning.lower()):
            return "DEGRADED"
    return "OK"


def _parity_css_class(status: str) -> str:
    return {"OK": "parity-ok", "DEGRADED": "parity-degraded", "INVALID": "parity-invalid"}.get(status, "")


def _has_low_confidence(rankings: list[ModelRanking]) -> bool:
    """Check if any dimension has low confidence."""
    for r in rankings:
        for ds in r.dimensions:
            if ds.statistical_verdict and ds.statistical_verdict.verdict.value == "insufficient_data":
                return True
            if ds.statistical_verdict and ds.statistical_verdict.sample_size < 5:
                return True
    return False


def _has_low_confidence_model(r: ModelRanking) -> bool:
    """Check if a specific model has low confidence on any dimension."""
    for ds in r.dimensions:
        if ds.statistical_verdict and ds.statistical_verdict.sample_size < 5:
            return True
    return False


def _is_tied_rank(r: ModelRanking, rankings: list[ModelRanking]) -> bool:
    """Check if this model's rank is tied with another."""
    return sum(1 for other in rankings if other.overall_rank == r.overall_rank) > 1


def _dimension_confidence(ds: DimensionScore) -> str:
    """Determine confidence level for a dimension score."""
    if ds.statistical_verdict:
        sv = ds.statistical_verdict
        if sv.sample_size >= 10:
            return "High"
        elif sv.sample_size >= 5:
            return "Medium"
        else:
            return "Low"
    return "Low"


def _collect_dimensions(rankings: list[ModelRanking]) -> list[Dimension]:
    """Collect all dimensions present across rankings."""
    dims: set[Dimension] = set()
    for r in rankings:
        for ds in r.dimensions:
            dims.add(ds.dimension)
    return sorted(dims, key=lambda d: d.value)


def _compute_normalization_ranges(
    rankings: list[ModelRanking],
    dims: list[Dimension],
) -> dict[Dimension, tuple[float, float]]:
    """Compute min/max per dimension for normalization (Review #4)."""
    ranges: dict[Dimension, tuple[float, float]] = {}
    for dim in dims:
        values = []
        for r in rankings:
            for ds in r.dimensions:
                if ds.dimension == dim:
                    values.append(ds.score)
        if values:
            ranges[dim] = (min(values), max(values))
        else:
            ranges[dim] = (0.0, 1.0)
    return ranges


def _normalize_score(
    raw: float,
    dim: Dimension,
    ranges: dict[Dimension, tuple[float, float]],
    is_inverted: bool,
) -> float:
    """Normalize a raw score to 0.0-1.0 for color mapping (Review #4)."""
    lo, hi = ranges.get(dim, (0.0, 1.0))

    # Score-type dimensions (0-1 range naturally)
    if dim not in INVERTED_DIMENSIONS and hi <= 1.0:
        norm = raw  # Already 0-1
    elif hi > lo:
        norm = (raw - lo) / (hi - lo)
    else:
        norm = 0.5

    # Invert for inverted dimensions (lower raw = better = higher norm)
    if is_inverted:
        norm = 1.0 - norm

    return max(0.0, min(1.0, norm))


def _heatmap_color(norm: float) -> str:
    """Map normalized 0-1 score to heatmap background color."""
    if norm >= 0.8:
        return "rgba(110,231,183,0.25)"
    elif norm >= 0.6:
        return "rgba(110,231,183,0.12)"
    elif norm >= 0.4:
        return "rgba(251,191,36,0.12)"
    elif norm >= 0.2:
        return "rgba(248,113,113,0.12)"
    else:
        return "rgba(248,113,113,0.25)"


def _format_raw_value(raw: float, dim: Dimension) -> str:
    """Format raw value for display based on dimension type."""
    if dim == Dimension.RESPONSE_LATENCY:
        return f"{raw:.0f}ms"
    elif dim == Dimension.COST_EFFICIENCY:
        return f"${raw:.4f}"
    elif dim == Dimension.CRITICAL_FAILURE_RATE:
        return f"{raw:.0%}"
    else:
        return f"{raw:.3f}"


