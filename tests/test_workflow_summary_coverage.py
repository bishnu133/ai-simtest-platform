class TestWorkflowCoverageEdgeCases:
    """Edge cases and boundary conditions."""

    def test_single_conversation_single_step(self):
        from src.coverage.workflow_coverage import analyze_workflow_coverage
        exports = [{
            "workflow": "Simple", "domain": "test",
            "total_conversations": 1, "passed": 1, "failed": 0,
            "avg_score": 1.0, "critical_failures": 0,
            "results": [{
                "status": "passed",
                "step_results": [{"step_name": "OnlyStep", "step_id": "s1", "status": "completed", "required": True}],
            }],
        }]
        wc = analyze_workflow_coverage(exports)
        assert wc.score == pytest.approx(1.0, abs=0.01)
        assert wc.steps_exercised == 1
        assert wc.steps_never_exercised == 0

