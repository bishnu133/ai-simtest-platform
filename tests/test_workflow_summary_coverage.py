def _sample_workflow_exports(n_workflows=1, n_convos=5, pass_rate=0.8):
    """Generate sample workflow export dicts for testing."""
    exports = []
    for i in range(n_workflows):
        passed = int(n_convos * pass_rate)
        failed = n_convos - passed
        results = []
        for j in range(n_convos):
            is_pass = j < passed
            results.append({
                "workflow": f"Test Workflow {i+1}",
                "domain": "customer_service",
                "passed": is_pass,
                "status": "passed" if is_pass else "failed",
                "score": 0.85 if is_pass else 0.45,
                "step_score": 0.9 if is_pass else 0.4,
                "rule_score": 1.0 if is_pass else 0.5,
                "condition_score": 0.8 if is_pass else 0.3,
                "completed_steps": ["Greeting", "Identify Issue", "Resolve"],
                "missed_steps": [] if is_pass else ["Confirm Resolution"],
                "violations": [] if is_pass else ["Required phrase missing"],
                "critical_failure": False,
                "critical_failures_count": 0,
                "workflow_applicable": True,
                "step_results": [
                    {"step_name": "Greeting", "step_id": "s1", "status": "completed", "required": True},
                    {"step_name": "Identify Issue", "step_id": "s2", "status": "completed", "required": True},
                    {"step_name": "Resolve", "step_id": "s3", "status": "completed" if is_pass else "missed", "required": True},
                    {"step_name": "Confirm Resolution", "step_id": "s4", "status": "completed" if is_pass else "missed", "required": True},
                    {"step_name": "Follow Up", "step_id": "s5", "status": "partial", "required": False},
                ],
            })

        exports.append({
            "workflow": f"Test Workflow {i+1}",
            "domain": "customer_service",
            "total_conversations": n_convos,
            "passed": passed,
            "failed": failed,
            "avg_score": round((0.85 * passed + 0.45 * failed) / n_convos, 3),
            "critical_failures": 0,
            "results": results,
        })
    return exports


